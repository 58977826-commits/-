def _component_dict(row: tuple) -> dict:
    cid, name, ctype, source, types, services, inputs, outputs, variables, risks, maturity = row
    md_file = f"components_md/{cid}_{name.replace(' ', '_')[:40]}.md"
    return {
        "组件编号": cid,
        "组件名称": name,
        "组件类型": ctype,
        "来源项目": source,
        "适用项目类型": types,
        "对应服务项": services,
        "输入数据": inputs,
        "输出物": outputs,
        "关键变量": variables,
        "风险点": risks,
        "是否标准组件": True,
        "成熟度": maturity,
        "AI摘要文件": md_file,
    }


